let isSubmittingCustomService = false;
function normalizeInputUrl(raw) {
  if (!raw || typeof raw !== 'string') return '';
  let str = raw.trim();
  if (!str) return '';
  const schemeMatch = /^([a-zA-Z][a-zA-Z0-9+.-]*):/i.exec(str);
  if (schemeMatch) {
    const scheme = schemeMatch[1].toLowerCase();
    if (scheme !== 'http' && scheme !== 'https') {
      return '';
    }
  } else {
    str = 'https://' + str;
  }
  try {
    const u = new URL(str);
    if (!['http:', 'https:'].includes(u.protocol) || u.username || u.password) return '';
    return u.href;
  } catch {
    return '';
  }
}

async function submitCustomService() {
  if (isSubmittingCustomService) return;
  const label = (customServiceLabelInput?.value || '').trim();
  const rawServiceUrl = (customServiceUrlInput?.value || '').trim();
  const rawLoginUrl = (customServiceLoginUrlInput?.value || '').trim();
  const iconKey = selectedCustomIcon || 'zchat';

  if (!label) {
    showCustomServiceError(currentLang === 'en' ? 'Service name is required.' : 'Tên dịch vụ không được để trống.');
    customServiceLabelInput?.focus();
    return;
  }
  if (label.length > 32) {
    showCustomServiceError(currentLang === 'en' ? 'Service name must be at most 32 characters.' : 'Tên dịch vụ tối đa 32 ký tự.');
    customServiceLabelInput?.focus();
    return;
  }
  if (!rawServiceUrl) {
    showCustomServiceError(currentLang === 'en' ? 'Service URL is required.' : 'Link dịch vụ không được để trống.');
    customServiceUrlInput?.focus();
    return;
  }

  const serviceUrl = normalizeInputUrl(rawServiceUrl);
  if (!serviceUrl) {
    showCustomServiceError(currentLang === 'en' ? 'Invalid service URL.' : 'Link dịch vụ không hợp lệ.');
    customServiceUrlInput?.focus();
    return;
  }

  let loginUrl = null;
  if (rawLoginUrl) {
    loginUrl = normalizeInputUrl(rawLoginUrl);
    if (!loginUrl) {
      showCustomServiceError(currentLang === 'en' ? 'Invalid login URL.' : 'Link đăng nhập không hợp lệ.');
      customServiceLoginUrlInput?.focus();
      return;
    }
  }

  if (customServiceUrlInput) customServiceUrlInput.value = serviceUrl;
  if (customServiceLoginUrlInput && loginUrl) customServiceLoginUrlInput.value = loginUrl;

  showCustomServiceError('');
  isSubmittingCustomService = true;
  if (customServiceSaveBtn) customServiceSaveBtn.disabled = true;
  try {
    const result = await command({
      action: 'custom_service_create',
      label,
      service_url: serviceUrl,
      login_url: loginUrl,
      icon_key: iconKey
    });

    if (result && result.ok) {
      closeCustomServicePanel();
    } else {
      const errorMap = {
        invalid_custom_service: currentLang === 'en' ? 'Invalid service parameters.' : 'Thông tin dịch vụ không hợp lệ.',
        max_custom_services_reached: currentLang === 'en' ? 'Maximum custom services reached.' : 'Đã đạt giới hạn số lượng dịch vụ thủ công.'
      };
      showCustomServiceError(errorMap[result?.error] || result?.error || (currentLang === 'en' ? 'Failed to create service.' : 'Không thể tạo dịch vụ.'));
    }
  } finally {
    isSubmittingCustomService = false;
    if (customServiceSaveBtn) customServiceSaveBtn.disabled = false;
  }
}

